export function normalizeDialect(text) {
 let t = normalize(text);
 for (const [pattern, value] of phrases) t = t.replace(pattern, value);
 t = t.replace(/(^|\s)عم(?=\s+[يت])/gu, '$1');
 t = t.replace(/(^|\s)(لا|ما)(?=[يت](?:عمل|شتغل|سمع|فتح|رسل|ستقبل|دخل|طبع|طلع|وصل|وجد|عرض|تعرف|ستجيب))/gu, '$1$2 ');
 return t.replace(/\s+/gu, ' ').trim();
}
export function shortAnswer(text) {
 const t = normalizeDialect(text);
 if (/^(?:نعم|اي|ايه|ايوه|ايوا|اي نعم|اي والله|اه|اها|بلى|انعم|اجل|يب|صح|صحيح|yes|yeah|yep)$/u.test(t)) return 'yes';
 if (/^(?:لا|لاا|لأ|لا والله|كلا|مو|مش|no|nope)$/u.test(t)) return 'no';
 if (/^(?:تمام|طيب|ابشر|اوكي|اوك|حاضر|ماشي|ok|okay)$/u.test(t)) return 'ack';
 return null;
}
